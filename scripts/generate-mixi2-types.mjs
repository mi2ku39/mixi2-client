#!/usr/bin/env node
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import openapiTS from 'openapi-typescript'

const DEFAULT_OUTPUT = 'src/generated/mixi2-api-types.ts'

function readOption(name) {
  const index = process.argv.indexOf(name)
  if (index === -1) return undefined
  return process.argv[index + 1]
}

async function main() {
  const specUrl = readOption('--url') ?? process.env.MIXI2_OPENAPI_URL
  const outputPath = resolve(readOption('--out') ?? process.env.MIXI2_TYPES_OUTPUT ?? DEFAULT_OUTPUT)

  if (!specUrl) {
    throw new Error('OpenAPI URL is required. Set MIXI2_OPENAPI_URL or pass --url <openapi-url>.')
  }

  const ast = await openapiTS(specUrl)
  const content = `/* eslint-disable */\n/* Auto-generated by scripts/generate-mixi2-types.mjs */\n\n${ast}`

  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, content, 'utf8')

  console.log(`Generated TypeScript types from ${specUrl}`)
  console.log(`Output: ${outputPath}`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
